def gen_acts(existing):
    plan = [
        ("真心话", TRUTH_TPLS),
        ("大冒险", DARE_TPLS),
        ("情侣任务", TASK_TPLS),
        ("默契问答", QUIZ_TPLS),
    ]
    out = {}
    for cat, tpls in plan:
        old = existing.get(cat, [])
        banned = set(old)
        need = TARGET - len(old)
        got = fill(tpls, need, banned)
        out[cat] = got
        print("  %s：原有 %d + 新增 %d = %d" % (cat, len(old), len(got), len(old) + len(got)))
    return out


def gen_pool(existing_pools):
    BASE = {"表达": 1, "作息": 1, "趣味": 1, "云陪": 2, "跑腿": 2, "投喂": 2, "手作": 3, "承诺": 3, "寄送": 4, "见面时": 5}
    OFF = [0, 1, 0, -1, 0, 1, -1, 0]
    old_by_lv = {i: [] for i in range(1, 6)}
    for cat, meet, items in existing_pools:
        for i, t in enumerate(items):
            lv = BASE[cat] + OFF[i % 8]
            if meet and lv < 3:
                lv = 3
            lv = max(1, min(5, lv))
            old_by_lv[lv].append((cat, meet, t))
    out = {}
    # 全局去重：跨等级也不能重样（旧条目已占用的文本，新条目一律不再使用）
    banned = {t for items in old_by_lv.values() for _, _, t in items}
    for lv in range(1, 6):
        old = old_by_lv[lv]
        need = TARGET - len(old)
        got = fill(POOL_TPLS[lv], need, banned)
        # 生成句的 cat / meet 由句式族携带，这里回填
        rows = []
        for tpl in POOL_TPLS[lv]:
            for s in expand(tpl):
                pass  # 只为保持可读性；实际映射在下面按文本查
        # 建立 文本 -> (cat, meet) 映射
        mapping = {}
        for tpl in POOL_TPLS[lv]:
            for s in expand(tpl):
                s = s.strip()
                mapping.setdefault(s, (tpl["cat"], tpl["meet"]))
        for g in got:
            cat, meet = mapping.get(g, ("表达", False))
            rows.append((cat, meet, g))
        out[lv] = old + rows
        print("  等级 %d：原有 %d + 新增 %d = %d" % (lv, len(old), len(rows), len(old) + len(rows)))
    return out


