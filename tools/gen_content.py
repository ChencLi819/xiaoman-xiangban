# ────────────────────────── 基础工具 ──────────────────────────

def expand(tpl):
    """把 (pattern, slots) 展开成候选句列表。"""
    pat, slots = tpl["pat"], tpl.get("slots", [])
    out = []
    idx = [0] * len(slots)
    if not slots:
        return [pat]
    while True:
        out.append(pat.format(*[s[i] for s, i in zip(slots, idx)]))
        # 进制递增
        for k in range(len(slots) - 1, -1, -1):
            idx[k] += 1
            if idx[k] < len(slots[k]):
                break
            idx[k] = 0
        else:
            return out


def existing_items():
    """解析 SeedData.kt，拿到原有条目（用于去重与计数）。"""
    src = open(SEED_DATA, encoding="utf-8").read()
    acts, pools = {}, []
    for kind, cat, meet, body in re.findall(
        r'(ActGroup|PoolGroup)\("([^"]+)",\s*(true|false)?,?\s*listOf\((.*?)\)\)', src, re.S
    ):
        items = re.findall(r'"((?:[^"\\]|\\.)*)"', body)
        if kind == "ActGroup":
            acts[cat] = items
        else:
            pools.append((cat, meet == "true", items))
    return acts, pools


BAD_PAT = re.compile(r"的的|了了|过过|寄寄|在在|和和|说说|做做|给给|帮帮|，，|。。|、、")


def valid(s):
    """挡掉模板拼接出来的病句（重复虚词、重复引号内容、长度过长）。"""
    if len(s) > 52 or s.count("「") != s.count("」"):
        return False
    if BAD_PAT.search(s):
        return False
    if re.search(r"「(.{1,6})」和「\1」", s):
        return False
    return True


def fill(templates, need, banned):
    """句式族轮流取样，补足 need 条；不足直接报错（不拿凑数的句子顶上）。"""
    fams = []
    for tpl in templates:
        cand = []
        seen_here = set()
        for s in expand(tpl):
            s = s.strip().replace("?", "？")
            if s in banned or s in seen_here or not valid(s):
                continue
            seen_here.add(s)
            cand.append(s)
        RNG.shuffle(cand)
        fams.append(cand)
    out = []
    while len(out) < need:
        progressed = False
        for fam in fams:
            if fam and len(out) < need:
                s = fam.pop(0)
                if s in banned:
                    continue
                out.append(s)
                banned.add(s)
                progressed = True
            if len(out) >= need:
                break
        if not progressed:
            raise SystemExit("候选句不足：还差 %d 条，请给对应的句式族加词库" % (need - len(out)))
    return out


def kotlin(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def block(lines, indent="            "):
    return "\n".join(indent + kotlin(s) + "," for s in lines)


